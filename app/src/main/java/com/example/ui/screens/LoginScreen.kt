@Composable
fun TwoFactorChallengeDialog(
    viewModel: MainViewModel,
    user: com.example.data.model.User
) {
    var pin by remember { mutableStateOf("") }
    var errorMessage by remember { mutableStateOf<String?>(null) }
    var isLoading by remember { mutableStateOf(false) }

    AlertDialog(
        onDismissRequest = { viewModel.logout() },
        title = {
            Row(verticalAlignment = Alignment.CenterVertically) {
                Icon(
                    imageVector = Icons.Default.Security,
                    contentDescription = null,
                    tint = MaterialTheme.colorScheme.primary
                )
                Spacer(modifier = Modifier.width(8.dp))
                Text("Verifikasi 2FA")
            }
        },
        text = {
            Column {
                Text(
                    text = "Akun ${user.username} diproteksi Otentikasi Dua Faktor. Masukkan 6 digit PIN keamanan Anda:",
                    style = MaterialTheme.typography.bodyMedium
                )
                Spacer(modifier = Modifier.height(16.dp))

                if (errorMessage != null) {
                    Text(
                        text = errorMessage!!,
                        color = MaterialTheme.colorScheme.error,
                        style = MaterialTheme.typography.bodySmall,
                        modifier = Modifier.padding(bottom = 8.dp)
                    )
                }

                OutlinedTextField(
                    value = pin,
                    onValueChange = {
                        if (it.length <= 6 && it.all { char -> char.isDigit() }) {
                            pin = it
                            errorMessage = null
                        }
                    },
                    label = { Text("6 Digit PIN 2FA") },
                    keyboardOptions = KeyboardOptions(keyboardType = KeyboardType.NumberPassword),
                    singleLine = true,
                    modifier = Modifier
                        .fillMaxWidth()
                        .testTag("two_factor_pin_input"),
                    shape = RoundedCornerShape(12.dp)
                )
            }
        },
        confirmButton = {
            Button(
                onClick = {
                    if (pin.length != 6) {
                        errorMessage = "Masukkan 6 digit angka PIN."
                        return@Button
                    }
                    isLoading = true
                    viewModel.verifyTwoFactor(pin) { success, msg ->
                        isLoading = false
                        if (!success) errorMessage = msg
                    }
                },
                enabled = !isLoading,
                modifier = Modifier.testTag("verify_two_factor_button")
            ) {
                if (isLoading) {
                    CircularProgressIndicator(modifier = Modifier.size(18.dp), strokeWidth = 2.dp)
                } else {
                    Text("Verifikasi")
                }
            }
        },
        dismissButton = {
            TextButton(onClick = { viewModel.logout() }) {
                Text("Batal")
            }
        }
    )
}
